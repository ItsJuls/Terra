package com.dfsek.terra.mod.mixin.spawn;

import com.dfsek.terra.mod.generation.MinecraftChunkGeneratorWrapper;
import net.minecraft.core.BlockPos;
import net.minecraft.tags.FluidTags;
import net.minecraft.world.level.LevelAccessor;
import net.minecraft.world.level.ServerLevelAccessor;
import net.minecraft.world.level.block.Blocks;


/**
 * Shared rule for {@link WaterCreatureSpawnMixin} and {@link WaterAnimalSpawnMixin}.
 * <p>
 * Vanilla only lets fish, squid and dolphins spawn naturally between sea level - 13 and sea level, so lakes and rivers
 * above sea level never get any. In worlds generated by Terra the height window is dropped and only the water check
 * is kept (water below, water above). Other worlds are unchanged. Turn it off with -Dterra.waterSpawnsAnyHeight=false.
 */
public final class TerraWaterSpawns {
    private static final boolean ENABLED = !"false".equalsIgnoreCase(System.getProperty("terra.waterSpawnsAnyHeight"));

    private TerraWaterSpawns() {
    }

    /** null = use vanilla's rule, otherwise the answer for this position */
    public static Boolean anyHeight(LevelAccessor world, BlockPos pos) {
        if(!ENABLED || !(world instanceof ServerLevelAccessor serverWorld)) return null;
        if(!(serverWorld.getLevel().getChunkSource().getGenerator() instanceof MinecraftChunkGeneratorWrapper)) return null;
        return world.getFluidState(pos.below()).is(FluidTags.WATER) && world.getBlockState(pos.above()).is(Blocks.WATER);
    }
}
